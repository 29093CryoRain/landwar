#!/usr/bin/env python3
"""生成 Arch31212 L9/L10 的反变体（偏移旋转 180°）。

当前 Config：
- L9 = shape 3（三角形锚，7 格）
- L10 = shape 4（十二边形锚，16 格）
正反两情况：锚朝向变换已自动产生 L9 正反（b=0/4 正、b=3/5 反），但用户要求每级
显式两个变体（保证两种形态都能看到）。反变体 = 正变体偏移绕锚旋转 180°。
"""
import math

# 当前 Config 偏移（旧中间朝向存储；运行时 (dx,dy)→(-dy,dx)）
L9 = [(-1.074569936353, 0.0), (-0.537284965912, -0.930604859102),
      (-0.537284965912, 0.930604740898), (0.0, 0.0),
      (0.537284965912, -0.930604859102), (0.537284965912, 0.930604740898),
      (1.074569931824, 0.0)]
L10 = [(-2.686424834088, -0.930604859102), (-2.686424834088, 0.930604740898),
       (-2.149139868177, -1.8612096), (-2.149139868177, 0.0),
       (-2.149139868177, 1.8612096), (-1.611854897736, -0.930604859102),
       (-1.611854897736, 0.930604740898), (-1.074569931824, -1.8612096),
       (-1.074569931824, 0.0), (-1.074569931824, 1.8612096),
       (-0.537284965912, -0.930604859102), (-0.537284965912, 0.930604740898),
       (0.0, 0.0), (0.537284965912, -0.930604859102),
       (0.537284965912, 0.930604740898), (1.074569931823, 0.0)]


def fmt(offs):
    return '{' + ', '.join('{%.12f, %.12f, 0}' % o for o in offs) + '}'


def rotate180(offs):
    """Config 偏移旋转 180°：先还原运行时 (rx,ry)=(-dy,dx)，旋转 180° 后转回 (ry,-rx)。
    旋转 180° 在 Config 空间 = (dx,dy)→(-dx,-dy)（两次旋转抵消符号）。
    验证：运行时变换是线性的，180° 旋转后 (-dy,dx)→(-(-dy),-dx)=(dy,-dx)，
    转回 Config (ry,-rx)=(-dx,-dy)。所以 Config 空间直接取负。"""
    out = []
    for dx, dy in offs:
        out.append((round(-dx, 12), round(-dy, 12)))
    return out


for name, shape in [('L9', L9), ('L10', L10)]:
    print('%s 反变体 config = %s' % (name, fmt(rotate180(shape))))
    print('  格数 =', len(shape))
